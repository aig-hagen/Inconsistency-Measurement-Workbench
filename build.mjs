// Build script. Writes
//   dist/im-core.js            the core library as a UMD module (used by the Node tests)
//   site/                      the deployable website:
//     index.html
//     css-<version>/style.css  stylesheet       (version from package.json, so that
//     js-<version>/*.js        scripts           a new version is never served from a cache)
//     img/                     logos
//     im-web-<version>.tar.gz  the complete source code
import { readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync, copyFileSync, statSync, existsSync } from 'node:fs';
import { join, dirname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const root = dirname(fileURLToPath(import.meta.url));
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
const name = 'im-web-' + version;

// ---------------------------------------------------------------- core library
// The core is a named function so that the page can start the Web Worker from
// its source text (imCore.toString()), which also works for file:// pages.
const coreDir = join(root, 'src', 'core');
const coreFiles = readdirSync(coreDir).filter(f => f.endsWith('.js')).sort();
const coreBody = coreFiles.map(f => `// ===== ${f} =====\n` + readFileSync(join(coreDir, f), 'utf8')).join('\n');
const core = `/* Inconsistency Measurement core library ${version} (JavaScript port of TweetyProject measures, LGPL-3.0) */
function imCore() {
'use strict';
const IM = {};
${coreBody}
IM.version = '${version}';
return IM;
}
(function (root) {
  const IM = imCore();
  if (typeof module !== 'undefined' && module.exports) module.exports = IM;
  else root.IM = IM;
})(typeof self !== 'undefined' ? self : this);
`;
mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist', 'im-core.js'), core);
console.log('Wrote dist/im-core.js (' + coreFiles.length + ' core files)');

// ---------------------------------------------------------------- website
const ui = join(root, 'src', 'ui');
const site = join(root, 'site');
mkdirSync(site, { recursive: true });
for (const f of readdirSync(site)) {   // remove the output of earlier builds (other versions)
  if (/^(css|js)-|^im-web-.*\.tar\.gz$|^index\.html$|^img$/.test(f)) rmSync(join(site, f), { recursive: true, force: true });
}
const cssDir = 'css-' + version, jsDir = 'js-' + version;
mkdirSync(join(site, cssDir)); mkdirSync(join(site, jsDir)); mkdirSync(join(site, 'img'));
copyFileSync(join(ui, 'style.css'), join(site, cssDir, 'style.css'));
writeFileSync(join(site, jsDir, 'im-core.js'), core);
copyFileSync(join(ui, 'examples.js'), join(site, jsDir, 'examples.js'));
copyFileSync(join(ui, 'app.js'), join(site, jsDir, 'app.js'));
for (const f of readdirSync(join(ui, 'img'))) copyFileSync(join(ui, 'img', f), join(site, 'img', f));
const html = readFileSync(join(ui, 'index.template.html'), 'utf8')
  .replace(/__CSS__/g, cssDir).replace(/__JS__/g, jsDir)
  .replace(/__TARBALL__/g, name + '.tar.gz').replace(/__VERSION__/g, version);
writeFileSync(join(site, 'index.html'), html);

// ---------------------------------------------------------------- source tarball
// Everything needed to rebuild, test and re-validate the site; the validation
// data and compiled Java classes are left out (they are regenerated by the scripts).
const EXCLUDE = [/^site(\/|$)/, /^dist(\/|$)/, /^validation\/data(\/|$)/, /^validation\/java\/build[^/]*(\/|$)/, /(^|\/)\.DS_Store$/, /(^|\/)node_modules(\/|$)/, /(^|\/)\./];
function walk(dir, out) {
  for (const f of readdirSync(dir).sort()) {
    const abs = join(dir, f), rel = relative(root, abs).split(sep).join('/');
    if (EXCLUDE.some(re => re.test(rel))) continue;
    if (statSync(abs).isDirectory()) walk(abs, out); else out.push(rel);
  }
  return out;
}
const files = walk(root, []);

// minimal ustar writer (regular files only)
function tarHeader(path, size, mode, mtime) {
  const h = Buffer.alloc(512);
  let nm = path, prefix = '';
  if (Buffer.byteLength(nm) > 100) { const i = path.lastIndexOf('/'); prefix = path.slice(0, i); nm = path.slice(i + 1); }
  if (Buffer.byteLength(nm) > 100 || Buffer.byteLength(prefix) > 155) throw new Error('Path too long for tar: ' + path);
  const put = (s, off, len) => h.write(s, off, len, 'utf8');
  const oct = (n, len) => n.toString(8).padStart(len - 1, '0') + '\0';
  put(nm, 0, 100); put(oct(mode, 8), 100, 8); put(oct(0, 8), 108, 8); put(oct(0, 8), 116, 8);
  put(oct(size, 12), 124, 12); put(oct(mtime, 12), 136, 12); put('        ', 148, 8); put('0', 156, 1);
  put('ustar\0', 257, 6); put('00', 263, 2); put(prefix, 345, 155);
  let sum = 0; for (const b of h) sum += b;
  put(sum.toString(8).padStart(6, '0') + '\0 ', 148, 8);
  return h;
}
const parts = [];
for (const rel of files) {
  const abs = join(root, rel), st = statSync(abs), data = readFileSync(abs);
  parts.push(tarHeader(name + '/' + rel, data.length, (st.mode & 0o111) ? 0o755 : 0o644, Math.floor(st.mtimeMs / 1000)), data, Buffer.alloc((512 - data.length % 512) % 512));
}
parts.push(Buffer.alloc(1024));
const tgz = gzipSync(Buffer.concat(parts), { level: 9 });
writeFileSync(join(site, name + '.tar.gz'), tgz);

console.log('Wrote site/index.html, site/' + cssDir + '/, site/' + jsDir + '/ (' + Math.round(core.length / 1024) + ' KB core), site/img/');
console.log('Wrote site/' + name + '.tar.gz (' + files.length + ' files, ' + Math.round(tgz.length / 1024) + ' KB)');
if (existsSync(join(root, 'index.html'))) console.log('Note: ./index.html is an old single-file build; the site is now in site/.');
