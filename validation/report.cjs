function measureTable(res, ids, labels) {
  row(['Measure', 'Compared', 'Equal', 'Equal by convention', 'Differ', 'JS better optimum', 'Java timeout', 'Java exception']);
  row(['---', '---:', '---:', '---:', '---:', '---:', '---:', '---:']);
  for (const id of ids) {
    const s = res.stats[id];
    if (!s) continue;
    const compared = s.total - s.javaTimeout - s.javaError;
    row([labels && labels[id] ? labels[id] : '`' + id + '`', compared, s.match, s.convention || '', s.mismatch || (s.jsError ? s.jsError + ' (JS error)' : ''), s.jsBetter || '', s.javaTimeout || '', s.javaError || '']);
  }
}
function examples(res, id, k) {
  const d = res.details[id];
  if (!d) return;
  for (const x of d.mismatches.slice(0, k || 3)) {
    p('  - KB ' + x.kb + ' `' + res.kbs[x.kb].join(' ; ') + '`: Java ' + JSON.stringify(x.java) + ', JS ' + JSON.stringify(x.js));
  }
}
function errorList(res, id) {
  const d = res.details[id];
  if (!d) return;
  for (const [m, c] of Object.entries(d.javaErrors)) p('  - ' + c + ' × `' + m + '`');
}

